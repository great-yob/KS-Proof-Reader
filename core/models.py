# Gemini AI
# 청크 크기를 키워 대부분 문서가 단일 호출로 처리되도록 유도.
# Gemini 3.1 Flash Lite는 1M+ 컨텍스트, 64K 출력 토큰을 지원하므로 안전.
#
# ⚠⚠ **이 값을 재현율 개선 레버로 쓰지 말 것 — 실측으로 기각됨(2026-07-27).**
#   사용자 보고(실단어 오타 '재시→제시'·'부고→보고' 미탐)를 추적해 8개 크기를 풀문서로
#   스윕했고(실파일D 127,081자, 각 설정 3회 완전 동일 = temp 0+seed 재현성 확인), 가드
#   체인+3차 재검증 통과분을 한 건씩 수동 판정했다. 정밀도/재현율:
#       15000 → 92%/20%    10000 → 62%/15%    8000 → 76%/29%    7500 → 61%/20%
#        7000 → 52%/22%     6000 → 84%/29%    4500 → 70%/29%    3000 → 79%/49%
#   여기까지만 보면 6000이 최적으로 보인다. 그러나 **크기를 고정하고 경계만 반 칸 민**
#   대조군을 돌리자 결론이 뒤집혔다:
#       6000 기본 84%/29%  ↔  6000 위상이동 61%/20%   (공통 교정 자카드 23%)
#      15000 기본 92%/20%  ↔ 15000 위상이동 76%/24%   (자카드 19%)
#   → **크기가 같아도 경계 위치만 바뀌면 결과의 ~80%가 바뀐다.** 즉 위 스윕은 8개 '크기'가
#     아니라 8개 '경계 구성'을 측정한 것이고, 크기별 순위는 우연에 가깝다. 경계 2구성 평균은
#     15000 = 84%/22% vs 6000 = 72.5%/24.5% 로 오히려 현행이 낫다. 보고된 미탐도 크기 탓이
#     아니었다 — 위상이동 15000은 '재시→제시'를 잡았다.
#   ⚠ 따라서 이 상수를 보간·추정으로 바꾸면 안 되고, 바꿔서 얻을 것도 별로 없다.
#
# ⚠⚠ **'더 똑똑한 청커'라는 탈출구도 실측으로 닫혔다(2026-07-28) — 재시도 금지.**
#   위 결론의 후속으로 `(청커 × 크기 × 위상)` 격자를 실Gemini로 돌렸다(실파일D 127,081자,
#   144호출 + 실파일E 29호출). 청커 3종 = base(현행) / pres(문단 경계 유지, 2026-06-30 보류안,
#   gemini_checker._split_sentences 독스트링 참조) / struct(표 블록 불분할 + 제목 정렬; 실측
#   경계 진단으로 **블록 내부 절단 0·표 절단 0·제목 정렬 7/8** 확인). 위상 쌍 자카드:
#       base 15000 26% · base 6000 25% · pres 15000 25% · struct 15000 17% · struct 6000 8%
#   → 구조에 못박아도 흔들림이 **줄기는커녕 늘었고**, 어떤 청커도 26%를 넘지 못했다. 즉
#     범인은 '경계가 어디 떨어지나'가 아니라 **문서를 나눈다는 행위 자체**다. 분할은 어느 오류가
#     표면화될지를 정하는 제비뽑기이며 청커 설계로는 못 고친다. 상관하는 유일한 변수는 **청크
#     수**(적을수록 안정) — 그래서 15000이 현행값으로 남는다.
#   ⚠ 측정 신뢰성 통제 통과: base 4설정의 정밀도가 전날 수동 판정값(92/76/84/61%)과 네 자리
#     모두 일치 재현. 남은 레버는 청킹 밖이다(프롬프트 주의 유도 / 검수 카드 노출 정책).
#   ⚠ RPD 예산 참고: 15000이면 127K자 문서당 9회, 6000이면 21회(윤문 켜면 +16회). 무료 티어
#     500 RPD 기준 일 55문서 vs 23문서. 소진 시 3.1-flash-lite로 즉시 전환돼 실효 1,000 RPD
#     지만 그 뒤(2.5-flash-lite 20 RPD)는 절벽이다.
